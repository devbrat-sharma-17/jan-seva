export const DEFAULT_DEPARTMENT_ID: DepartmentId = 'roads';

export function getDepartmentConfig(id: string): DepartmentConfig {
  const norm = id.toLowerCase().trim() as DepartmentId;
  return DEPARTMENTS[norm] || DEPARTMENTS.roads;
}

export function getDepartmentByAIDept(aiDept: string): DepartmentConfig {
  const norm = aiDept.toLowerCase().trim();
  const match = Object.values(DEPARTMENTS).find((d) => d.aiDeptId === norm || d.id === norm);
  return match || DEPARTMENTS.roads;
}

export function getAllDepartments(): DepartmentConfig[] {
  return Object.values(DEPARTMENTS);
}
